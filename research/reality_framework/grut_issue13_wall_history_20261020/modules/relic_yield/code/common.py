# ----------------------------------------------------------------------------- potential and vertex tensors
def potential(h, q1, q2, D, alpha=ALPHA):
    phi = V + h
    X2 = 0.5 * (q1 * q1 + q2 * q2)
    return (LAM_PHI / 4.0 * (phi * phi - V * V) ** 2 + GX ** 2 * phi * phi * X2 + LAM_X * X2 * X2
            + 0.5 * (MD0 ** 2 + HD ** 2 * phi * phi) * D * D + LAM_D / 4.0 * D ** 4 + alpha * X2 * D * D)


def vertex_tensors(alpha=ALPHA):
    """Analytic third and fourth derivatives of U at the +v vacuum (real basis h,q1,q2,D). Derived."""
    L3 = np.zeros((4, 4, 4))
    L4 = np.zeros((4, 4, 4, 4))

    def sym3(i, j, k, val):
        for a, b, c in {(i, j, k), (i, k, j), (j, i, k), (j, k, i), (k, i, j), (k, j, i)}:
            L3[a, b, c] = val

    def sym4(i, j, k, l, val):
        import itertools
        for p in set(itertools.permutations((i, j, k, l))):
            L4[p] = val

    sym3(0, 0, 0, 6.0 * LAM_PHI * V)          # lam_phi v h^3
    sym3(0, 1, 1, 2.0 * GX ** 2 * V)          # 2 gX^2 v h |X|^2
    sym3(0, 2, 2, 2.0 * GX ** 2 * V)
    sym3(0, 3, 3, 2.0 * HD ** 2 * V)          # hD^2 v h D^2
    sym4(0, 0, 0, 0, 6.0 * LAM_PHI)
    sym4(0, 0, 1, 1, 2.0 * GX ** 2)
    sym4(0, 0, 2, 2, 2.0 * GX ** 2)
    sym4(1, 1, 1, 1, 6.0 * LAM_X)
    sym4(2, 2, 2, 2, 6.0 * LAM_X)
    sym4(1, 1, 2, 2, 2.0 * LAM_X)
    sym4(0, 0, 3, 3, 2.0 * HD ** 2)
    sym4(3, 3, 3, 3, 6.0 * LAM_D)
    if alpha != 0.0:
        sym4(1, 1, 3, 3, 2.0 * alpha)
        sym4(2, 2, 3, 3, 2.0 * alpha)
    return L3, L4


def numerical_tensors(step=1e-2, alpha=ALPHA):
    """Finite-difference derivatives of U at the vacuum (check of vertex_tensors)."""
    x0 = np.zeros(4)

    def U(x):
        return potential(x[0], x[1], x[2], x[3], alpha)

    E = np.eye(4) * step
    H2 = np.zeros((4, 4))
    L3 = np.zeros((4, 4, 4))
    L4 = np.zeros((4, 4, 4, 4))
    # U is a quartic polynomial: central differences with these stencils are exact up to roundoff
    for a in range(4):
        for b in range(4):
            H2[a, b] = (U(x0 + E[a] + E[b]) - U(x0 + E[a] - E[b]) - U(x0 - E[a] + E[b]) + U(x0 - E[a] - E[b])) / (4 * step ** 2)
    for a in range(4):
        for b in range(4):
            for c in range(4):
                s = 0.0
                for sa in (1, -1):
                    for sb in (1, -1):
                        for sc in (1, -1):
                            s += sa * sb * sc * U(x0 + sa * E[a] + sb * E[b] + sc * E[c])
                L3[a, b, c] = s / (8 * step ** 3)
    for a in range(4):
        for b in range(4):
            for c in range(4):
                for d in range(4):
                    s = 0.0
                    for sa in (1, -1):
                        for sb in (1, -1):
                            for sc in (1, -1):
                                for sd in (1, -1):
                                    s += sa * sb * sc * sd * U(x0 + sa * E[a] + sb * E[b] + sc * E[c] + sd * E[d])
                    L4[a, b, c, d] = s / (16 * step ** 4)
    return H2, L3, L4


# ----------------------------------------------------------------------------- Bose-Einstein thermodynamics
KMAX = 80
_K = np.arange(1, KMAX + 1, dtype=float)


def be_thermo(T, eta, m, g):
    """Bose-Einstein n, rho, P and derivatives for one species with chemical potential mu = eta*T.

    Series n = g T^3/(2pi^2) sum_k e^{k eta} x^2 K2(kx)/k, etc. (derived). Requires eta < x.
    Returns dict with n, rho, P, dn_deta, drho_deta, dn_dlnT, drho_dlnT (at fixed eta).
    """
    x = m / T
    k = _K
    kx = k * x
    w = np.exp(k * (eta - x))            # e^{k eta} e^{-k x}; Bessel functions are exponentially scaled
    K0 = kve(0, kx)
    K1 = kve(1, kx)
    K2 = kve(2, kx)
    c3 = g * T ** 3 / (2 * math.pi ** 2)
    c4 = c3 * T
    n = c3 * np.sum(w * x * x * K2 / k)
    P = c4 * np.sum(w * x * x * K2 / k ** 2)
    rho = c4 * np.sum(w * (x ** 3 * K1 / k + 3 * x * x * K2 / k ** 2))
    dn_deta = c3 * np.sum(w * x * x * K2)
    drho_deta = c4 * np.sum(w * (x ** 3 * K1 + 3 * x * x * K2 / k))
    dn_dlnT = 3 * n + c3 * np.sum(w * x ** 3 * K1)
    drho_dlnT = 4 * rho + c4 * np.sum(w * (x ** 3 * K1 / k + x ** 4 * K0))
    return dict(n=n, rho=rho, P=P, dn_deta=dn_deta, drho_deta=drho_deta, dn_dlnT=dn_dlnT, drho_dlnT=drho_dlnT)


def be_thermo_psi(T, psi, m, g):
    """Same as be_thermo but in the variable psi = (mu - m)/T (bounded, slowly varying for a frozen NR gas).

    Derivatives returned at fixed psi: dn_dlnT = dn/dlnT|_eta - x dn/deta, etc. (derived)."""
    x = m / T
    psi = min(psi, -1e-12)
    k = _K
    kx = k * x
    w = np.exp(k * psi)
    K0 = kve(0, kx)
    K1 = kve(1, kx)
    K2 = kve(2, kx)
    c3 = g * T ** 3 / (2 * math.pi ** 2)
    c4 = c3 * T
    n = c3 * np.sum(w * x * x * K2 / k)
    P = c4 * np.sum(w * x * x * K2 / k ** 2)
    rho = c4 * np.sum(w * (x ** 3 * K1 / k + 3 * x * x * K2 / k ** 2))
    dn_deta = c3 * np.sum(w * x * x * K2)
    drho_deta = c4 * np.sum(w * (x ** 3 * K1 + 3 * x * x * K2 / k))
    dn_dlnT = 3 * n + c3 * np.sum(w * x ** 3 * K1) - x * dn_deta
    drho_dlnT = 4 * rho + c4 * np.sum(w * (x ** 3 * K1 / k + x ** 4 * K0)) - x * drho_deta
    return dict(n=n, rho=rho, P=P, dn_dpsi=dn_deta, drho_dpsi=drho_deta, dn_dlnT=dn_dlnT, drho_dlnT=drho_dlnT)


def log_n0_mb(T, m, g=1.0):
    """log of the MB number density at mu = 0 without its exp(-m/T) factor."""
    x = m / T
    return math.log(g * m * m * T * kve(2, x) / (2 * math.pi ** 2))


def n_mb(T, m, g=1.0):
    """Maxwell-Boltzmann equilibrium number density at mu = 0."""
    x = m / T
    return g * m * m * T * kve(2, x) * math.exp(-x) / (2 * math.pi ** 2)


