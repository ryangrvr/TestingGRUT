"""Lossless archive of all scalar/topology/configuration diagnostics and mode tables.

End slices are visualization aids; full f32 slices stay local and are regenerated by
the solver. Their hashes and explicit non-archival status are recorded.
"""
from pathlib import Path
import hashlib,json,tarfile,sys
HERE=Path(__file__).resolve().parent
RAW=HERE/'raw'

def main():
    files=sorted(p for p in RAW.iterdir() if p.is_file())
    included=[p for p in files if p.suffix!='.f32']
    with tarfile.open(HERE/'raw_diagnostics.tar.gz','w:gz') as tf:
        for p in included:tf.add(p,arcname='raw/'+p.name)
    entries=[]
    for p in files:
        entries.append({'path':'raw/'+p.name,'bytes':p.stat().st_size,
                        'sha256':hashlib.sha256(p.read_bytes()).hexdigest(),
                        'archived':p.suffix!='.f32',
                        'scope':'full scalar/config/topology/mode diagnostic' if p.suffix!='.f32' else 'visualization-only central slice; regenerate with source'})
    result={'archive':'raw_diagnostics.tar.gz','archive_sha256':hashlib.sha256((HERE/'raw_diagnostics.tar.gz').read_bytes()).hexdigest(),
            'archive_bytes':(HERE/'raw_diagnostics.tar.gz').stat().st_size,'archived_files':len(included),'files':entries,
            'full_3D_field_states_archived':False,'scope':'No full evolving fields were saved; raw scalar and topology diagnostics are losslessly included.'}
    (HERE/'RAW_MANIFEST.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps({'archive_bytes':result['archive_bytes'],'files':len(files),'archived':len(included)}))

def unpack():
    record=json.loads((HERE/'RAW_MANIFEST.json').read_text())
    expected={x['path']:x for x in record['files'] if x['archived']}
    with tarfile.open(HERE/record['archive'],'r:gz') as tf:
        members={m.name:m for m in tf.getmembers() if m.isfile()}
        if set(members)!=set(expected):raise ValueError('archive leaf paths differ')
        for name,member in members.items():
            parts=Path(name).parts
            if len(parts)!=2 or parts[0]!='raw' or '..' in parts:raise ValueError('unsafe archive path')
            payload=tf.extractfile(member).read();entry=expected[name]
            if len(payload)!=entry['bytes'] or hashlib.sha256(payload).hexdigest()!=entry['sha256']:raise ValueError('hash mismatch: '+name)
            target=HERE/name;target.parent.mkdir(exist_ok=True);target.write_bytes(payload)
    print('Unpacked',len(expected),'lossless diagnostics')

if __name__=='__main__':
    if len(sys.argv)>1 and sys.argv[1]=='unpack':unpack()
    else:main()
