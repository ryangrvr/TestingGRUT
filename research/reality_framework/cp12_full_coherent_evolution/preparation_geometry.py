"""Sample the exact initial diagonal graph distribution, not quantum dynamics.

The reference 0 is isolated. Uniform Q-subsets of edges on the other N-1 sites
are generated by rejection sampling independent uniform endpoint pairs.
"""
from pathlib import Path
import random,json,math,statistics
from collections import deque

def sample(n,q,rng):
 es=set()
 while len(es)<q:
  i,j=rng.sample(range(1,n),2);es.add(tuple(sorted((i,j))))
 adj=[[] for _ in range(n)]
 for i,j in es:adj[i].append(j);adj[j].append(i)
 seen=set();comps=[]
 for i in range(n):
  if i in seen:continue
  group=[i];seen.add(i)
  for v in group:
   for w in adj[v]:
    if w not in seen:seen.add(w);group.append(w)
  comps.append(group)
 giant=max(comps,key=len);means=[];ecc=[]
 for root in rng.sample(giant,min(8,len(giant))):
  ds={root:0};todo=deque([root])
  while todo:
   v=todo.popleft()
   for w in adj[v]:
    if w not in ds:ds[w]=ds[v]+1;todo.append(w)
  means.append(sum(ds.values())/max(1,len(ds)-1));ecc.append(max(ds.values()))
 return dict(largest_fraction=len(giant)/n,isolated_fraction=sum(not a for a in adj)/n,
             maximum_degree=max(map(len,adj)),sampled_mean_distance=statistics.mean(means),
             sampled_diameter_lower_bound=max(ecc))

if __name__=='__main__':
 rng=random.Random(12012026);result=[]
 for n in [64,256,1024,4096]:
  samples=[sample(n,n-1,rng) for _ in range(100)]
  row=dict(N=n,Q=n-1,samples=100,means={k:statistics.mean(s[k] for s in samples) for k in samples[0]},
           standard_errors={k:statistics.stdev(s[k] for s in samples)/10 for k in samples[0]})
  result.append(row);print(json.dumps(row),flush=True)
 (Path(__file__).with_name('preparation_geometry_results.json')).write_text(json.dumps(result,indent=2)+'\n')
