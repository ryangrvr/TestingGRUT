"""Fill the FULLTABLE / REDTABLE / SEEDTABLE / LARGESECTION placeholders in NOTES.md from results/*.json."""
import json
import sys
from pathlib import Path

A = Path(__file__).resolve().parent
R = A / 'results'
runs = Path(sys.argv[1])
notes = (A / 'NOTES.md').read_text()
wall = {f.name[:-9]: json.loads(f.read_text())['wall_seconds'] for f in runs.glob('*.cmd.json')}
COUNT = ['fplus_04', 'fminus_04', 'fplus_05', 'fminus_05', 'fplus_06', 'fminus_06', 'genuine_plus', 'genuine_minus', 'min_S', 'max_S']
lines = []
for f in sorted(R.glob('rerun_full_*.json')):
    n = f.name[len('rerun_full_'):-5]
    r = json.loads(f.read_text())
    mx = max([v['max_rel'] for k, v in r['differing_columns'].items() if k not in ('mean_S', 'linear_chi_projection')] + [0])
    s, a = r['rerun_summary'], r['archive_summary']
    lines.append(f"| {n} | {all(c in r['bitwise_identical_columns'] for c in COUNT)} | {r['topology_records_identical']} ({r['topology_records'][0]}) | {mx:.1e} | {s['charge_rel_drift_max']:.2e} / {a['charge_rel_drift_max']:.2e} | {s['budget_pointwise']:.4g} / {a['budget_pointwise']:.4g} | {wall['full_' + n]:.0f} |")
notes = notes.replace('FULLTABLE', '\n'.join(lines))


def row(n):
    r = json.loads((R / f'rerun_{n}.json').read_text())
    af = 'none' if r['a_form'] is None else f"{r['a_form']:.2f}"
    return (f"| {n} | {af} | {r['end_fplus_05']:.4f} | {r['end_fminus_05']:.3g} | {r['max_fminus_05']:.4f} ({r['a_at_max_fminus_05']:.2f}) | "
            f"{r.get('end_winding_plus_any')}/{r.get('end_winding_minus_any')} | {r.get('both_wind_all_every_post_record', 'n/a')} | "
            f"{r['charge_rel_drift_max']:.2e} | {r['budget_pointwise']:.3e} |")


red = ['red128dx06_main_s101', 'red96dx08_main_s101', 'red128dx06_gaussian_s202', 'red96dx08_gaussian_s202',
       'red128dx04_main_s101', 'red128dx04_gaussian_s202']
notes = notes.replace('REDTABLE', '\n'.join(row(n) for n in red))
hdr = ('| run | a_form | end f+ | end f- | max f- (a) | end winding +/- | 7/7 at every post-formation record | charge drift | budget |\n'
       '|---|---|---|---|---|---|---|---|---|\n')
seeds = ['seed128dx04_gaussian_s303', 'seed128dx04_gaussian_s404', 'seed128dx04_gaussian_s505', 'red128dx04_gaussian_s202',
         'red128dx04_main_s101', 'red128dx04_main_s202', 'seed128dx04_main_s303', 'seed128dx04_main_s404', 'seed128dx04_main_s505']
notes = notes.replace('SEEDTABLE', hdr + '\n'.join(row(n) for n in seeds))
large = [n for n in ('new_large_s202', 'new_large_s303') if (R / f'rerun_{n}.json').exists()]
sec = ('### Large-box rows Codex left unexecuted (N=288, dx=0.4, L=115.2; frozen source, archived argument set) [E]\n\n'
       'Codex\'s RUN_STATUS lists large_s202 and large_s303 as `not_launched_cost_cap`. Run here with the same\n'
       'arguments as large_s101 (modes regenerated by the same recipe for L=115.2: s202 sha256 8f8e746f...,\n'
       's303 e87bb60d...). New evidence, not a reproduction.\n\n' + hdr + '\n'.join(row(n) for n in large))
notes = notes.replace('LARGESECTION', sec)
(A / 'NOTES.md').write_text(notes)
print('filled', len(lines), 'full rows;', large)
