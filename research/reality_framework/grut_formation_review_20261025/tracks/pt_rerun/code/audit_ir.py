"""Audit (a): infrared width prescription and canonical covariance of the 5f5513b preparation.

Own analysis code (Claude, pt_rerun). It reads Codex's published PREPARATION_L*.npz factors and the
old MATCH_L12.npz, and (for the whitening test) fields generated by Codex's prepare.initialize.
Usage: python3 -B audit_ir.py <packet_dir> <early_packet_dir> <initial.npy of IR12_s1_w1 rerun> <out.json>
"""
import sys, json
import numpy as np
from scipy.fft import fftn
from scipy.stats import chi2 as CHI2

pk, early, init_path, out = sys.argv[1:5]
res = {}

# ---------------------------------------------------------------- 1. purity of the initial Gaussian (independent formula)
d12 = np.load(f'{pk}/PREPARATION_L12.npz'); d24 = np.load(f'{pk}/PREPARATION_L24.npz')
lam = d12['initial_mass_eigenvalues']; U = d12['initial_mass_eigenvectors']
J = np.block([[np.zeros((6, 6)), np.eye(6)], [-np.eye(6), np.zeros((6, 6))]])
res['initial_eigenvalues'] = lam.tolist()
res['obstruction_k'] = np.sqrt(-lam[lam < 0]).tolist()
res['U_orthogonality_error'] = float(np.max(abs(U.T @ U - np.eye(6))))
res['U_diagonalises_M0_check'] = 'eigenvectors as columns; U^T U = 1 to the value above'


def omegas(k, width):
    w2 = k * k + lam
    return np.sqrt(np.where(w2 > 0, w2, k * k + width * width))


def S_matrix(k, width):
    w = omegas(k, width)
    S = np.zeros((12, 12)); S[:6, :6] = U / np.sqrt(2 * w)[None, :]; S[6:, 6:] = U * np.sqrt(w / 2)[None, :]
    return S


worst_symp = 0.; worst_det = 0.
for d, L in [(d12, 12.), (d24, 24.)]:
    for k in d['ks']:
        for width in (1., 3.):
            S = S_matrix(k, width); V = S @ S.T  # covariance of (q,p) for unit-variance real quadratures
            # Williamson symplectic eigenvalues of V: |eig(i J V)|; pure state <=> all equal 1/2
            nu = np.sort(abs(np.linalg.eigvals(1j * J @ V)))
            worst_symp = max(worst_symp, float(np.max(abs(nu - .5))))
            # per eigen-direction 2x2 determinant in the Hessian eigenbasis
            Vq = U.T @ V[:6, :6] @ U; Vp = U.T @ V[6:, 6:] @ U
            worst_det = max(worst_det, float(np.max(abs(np.diag(Vq) * np.diag(Vp) - .25))))
            worst_det = max(worst_det, float(np.max(abs(Vq - np.diag(np.diag(Vq))))), float(np.max(abs(Vp - np.diag(np.diag(Vp))))))
res['purity'] = dict(max_symplectic_eigenvalue_minus_half=worst_symp, max_eigenbasis_det_minus_quarter_or_offdiag=worst_det,
                     note='unit-variance real quadratures; a complex standard normal z=(n1+i n2)/sqrt2 gives E|z|^2=1, E z^2=0, i.e. the same covariance per Fourier mode pair')

# ---------------------------------------------------------------- 2. unstable/stable split, counts
rows = []
for d, L in [(d12, 12.), (d24, 24.)]:
    ks = d['ks']; uns = ks[:, None] ** 2 + lam[None, :] <= 0
    rows.append(dict(L=L, shells=len(ks), unstable_oscillators_dir0=int(uns[:, 0].sum()), unstable_oscillators_dir1=int(uns[:, 1].sum()),
                     max_k_unstable_dir0=float(ks[uns[:, 0]].max()), max_k_unstable_dir1=float(ks[uns[:, 1]].max()),
                     smallest_stable_Omega=float(np.sqrt(np.min(np.where(uns, np.inf, ks[:, None] ** 2 + lam))))))
res['split'] = rows

# ---------------------------------------------------------------- 3. recover light transfer rows; width only enters via S
def transfer_light(d, width_key, width):
    F = d[width_key]; ks = d['ks']; T = np.zeros((len(ks), 4, 12))
    for i, k in enumerate(ks):
        T[i] = F[i][[0, 1, 3, 4], :12] @ np.linalg.inv(S_matrix(k, width))
    return T

consistency = {}
for d, L in [(d12, 12.), (d24, 24.)]:
    T1 = transfer_light(d, 'factor_width1', 1.); T3 = transfer_light(d, 'factor_width3', 3.)
    new = np.ones(len(d['ks']), bool)
    if L == 12.:
        old = np.load(f'{early}/MATCH_L12.npz'); new = ~np.isin(d['keys'], old['keys'])
    scale = np.max(abs(T1[new]), axis=(1, 2))
    consistency[f'L{L:g}'] = float(np.max(np.max(abs(T1[new] - T3[new]), axis=(1, 2)) / scale))
    # phi columns identical for both widths
    consistency[f'L{L:g}_phi_cols_identical'] = bool(np.array_equal(d['factor_width1'][:, :, 12:], d['factor_width3'][:, :, 12:]))
res['transfer_recovered_from_w1_vs_w3_max_relative'] = consistency

# ---------------------------------------------------------------- 4. continuity: L24 (new code path) vs L12 old seeded band at equal k
old = np.load(f'{early}/MATCH_L12.npz')
look12 = {int(k): i for i, k in enumerate(d12['keys'])}; look24 = {int(k): i for i, k in enumerate(d24['keys'])}
cont = []
for key12 in d12['keys']:
    key24 = 4 * int(key12)
    if key24 not in look24: continue
    a = d12['factor_width1'][look12[int(key12)]]; b = d24['factor_width1'][look24[key24]]
    # compare covariances (sign/phase of factor columns is fixed by U, so compare factors directly too)
    Ca = a @ a.T; Cb = b @ b.T
    cont.append(dict(k=float(d12['ks'][look12[int(key12)]]), old_band=bool(int(key12) in set(old['keys'].tolist())),
                     factor_rel=float(np.max(abs(a - b)) / np.max(abs(a))), cov_rel=float(np.max(abs(Ca - Cb)) / np.max(abs(Ca)))))
res['L24_vs_L12_same_k'] = dict(max_factor_rel_old_band=max(c['factor_rel'] for c in cont if c['old_band']),
                                max_factor_rel_new_band=max(c['factor_rel'] for c in cont if not c['old_band']),
                                max_cov_rel_all=max(c['cov_rel'] for c in cont), n_compared=len(cont))

# ---------------------------------------------------------------- 5. per-mode expected tau=20 charged variance vs k (continuity at 1.414/1.683/1.8)
mq = d12['light_mean_q']; mp = d12['light_mean_p']; r0 = np.linalg.norm(mq[:2]); p0 = np.linalg.norm(mp[:2])
prof = {}
for d, L in [(d12, 12.), (d24, 24.)]:
    for wk in ['factor_width1', 'factor_width3']:
        F = d[wk]; C = np.einsum('kia,kja->kij', F, F)
        v = C[:, 0, 0] + C[:, 1, 1]; vp = C[:, 3, 3] + C[:, 4, 4]
        prof[f'L{L:g}_{wk}'] = dict(k=d['ks'].tolist(), q_var_per_mode=v.tolist(), p_var_per_mode=vp.tolist())
# shell totals and k<1.8 shares
shares = {}
for d, L in [(d12, 12.), (d24, 24.)]:
    for wk in ['factor_width1', 'factor_width3']:
        F = d[wk]; C = np.einsum('k,kia,kja->kij', d['degeneracy'] / L ** 3, F, F)
        q = C[:, 0, 0] + C[:, 1, 1]; p = C[:, 3, 3] + C[:, 4, 4]; lo = d['ks'] < 1.8
        shares[f'L{L:g}_{wk}'] = dict(q_RMS_over_mean=float(np.sqrt(q.sum()) / r0), p_RMS_over_mean=float(np.sqrt(p.sum()) / p0),
                                      q_RMS_old_band_only=float(np.sqrt(q[~lo].sum()) / r0), p_RMS_old_band_only=float(np.sqrt(p[~lo].sum()) / p0),
                                      q_variance_share_k_lt_1p8=float(q[lo].sum() / q.sum()), p_variance_share_k_lt_1p8=float(p[lo].sum() / p.sum()))
res['handoff_expected'] = shares
# shell profile near the band edge (L24, per mode, normalised to mean amplitude^2)
k24 = d24['ks']; F = d24['factor_width1']; C = np.einsum('kia,kja->kij', F, F); qv = (C[:, 0, 0] + C[:, 1, 1]) / 24 ** 3 / r0 ** 2
sel = (k24 > 1.2) & (k24 < 2.2)
res['L24_per_mode_q_variance_over_r0sq_near_edge'] = [[float(a), float(b)] for a, b in zip(k24[sel], qv[sel])]
F = d12['factor_width1']; C = np.einsum('kia,kja->kij', F, F); qv12 = (C[:, 0, 0] + C[:, 1, 1]) / 12 ** 3 / r0 ** 2
res['L12_per_mode_q_variance_over_r0sq_near_edge'] = [[float(a), float(b)] for a, b in zip(d12['ks'][:16], qv12[:16])]

# ---------------------------------------------------------------- 6. width sensitivity sigma in {0.1..30} (TT recovered from the published factor)
sens = {}
for d, L in [(d12, 12.), (d24, 24.)]:
    T = transfer_light(d, 'factor_width1', 1.); deg = d['degeneracy']; ks = d['ks']; Fphi = d['factor_width1'][:, :, 12:]
    out_s = []
    for sigma in [0.1, 0.3, 1., 2., 3., 5., 10., 30.]:
        q = p = 0.
        for i, k in enumerate(ks):
            Fl = T[i] @ S_matrix(k, sigma)  # rows chi1, chi2, pi1, pi2
            q += deg[i] / L ** 3 * (np.sum(Fl[0] ** 2) + np.sum(Fl[1] ** 2))
            p += deg[i] / L ** 3 * (np.sum(Fl[2] ** 2) + np.sum(Fl[3] ** 2))
        out_s.append(dict(sigma=sigma, q_RMS_over_mean=float(np.sqrt(q) / r0), p_RMS_over_mean=float(np.sqrt(p) / p0)))
    sens[f'L{L:g}'] = out_s
res['width_sensitivity'] = sens

# ---------------------------------------------------------------- 7. whitened covariance of generated fields
from whiten import whiten_test

wt = {}
z = np.load(init_path)
wt['IR12_s1_w1_rerun_initial'] = whiten_test(z, d12, 'factor_width1', 12., 32)
res['whitening'] = wt
json.dump(res, open(out, 'w'), indent=1)
print(json.dumps({k: v for k, v in res.items() if k not in ('L24_per_mode_q_variance_over_r0sq_near_edge',)}, indent=1)[:6000])
