"""en_rerun_skeptic -- own checks of the matched preparation (no Codex import), from Codex's published MATCH_L12.npz
and the tau-20 initial field of the N48 run (Codex initial.py output, as regenerated by en_rerun).
 (a) purity of the full 12x12 Gaussian and symplectic spectrum of the light X marginal, per shell;
 (b) expected X fluctuation variance (1/V) sum_n C_XX(k_n) and phi variance vs the realised N48 field;
 (c) per-shell chi^2 test of the realised X/phi Fourier power against the specified covariance (different from
     en_rerun's whitening test);
 (d) where the seeded X variance sits in k.
usage: python3 -I prep_checks.py <MATCH_L12.npz> <initial.bin> <out_json>"""
import sys, json
import numpy as np
from scipy import stats

m = np.load(sys.argv[1]); init = sys.argv[2]; outp = sys.argv[3]
keys = m['keys']; ks = m['ks']; E = m['evolved_scalar']; EP = m['evolved_phi']
L = 12.; V = L**3; N = 48
J2 = np.array([[0, 1], [-1, 0]])


def symp_eigs(Cm):
    n = Cm.shape[0]//2
    J = np.block([[np.zeros((n, n)), np.eye(n)], [-np.eye(n), np.zeros((n, n))]])
    ev = np.linalg.eigvals(1j*J @ Cm)
    return np.sort(abs(ev.real))[::2]


# covariance of the real quadratures: c = A z, z complex standard, E[c c^H] = A A^T (A real) -> symmetric real part
pur = []; xm = []
for A in E:
    Cfull = A @ A.T  # 12x12 (q1..q6, p1..p6), equals the symmetrised Wigner covariance of the evolved pure state
    pur.append(np.max(abs(symp_eigs(Cfull) - .5)))
    idx = [0, 1, 6, 7]
    xm.append(symp_eigs(Cfull[np.ix_(idx, idx)]))
xm = np.array(xm)
# expected variances: each +-n pair contributes 2 * C/V; count lattice multiplicities for |n|^2 in band (L=12, cutoff 8)
nmax = int(np.ceil(8*L/(2*np.pi))); a = np.arange(-nmax, nmax+1)
n2 = (a[:, None, None]**2 + a[None, :, None]**2 + a[None, None, :]**2).ravel()
kk = 2*np.pi/L*np.sqrt(n2); band = (kk >= 1.8) & (kk <= 8.)
mult = {int(v): int(c) for v, c in zip(*np.unique(n2[band], return_counts=True))}
lookup = {int(v): i for i, v in enumerate(keys)}
CXX = np.array([np.sum(E[i][[0, 1]]**2) for i in range(len(keys))])     # (A A^T)_00 + (A A^T)_11
Cphi = np.array([np.sum(EP[i][0]**2) for i in range(len(keys))])
multv = np.array([mult.get(int(k), 0) for k in keys])
expX = float(np.sum(multv*CXX)/V); expP = float(np.sum(multv*Cphi)/V)
share = multv*CXX/np.sum(multv*CXX)
# realised field
with open(init, 'rb') as f:
    f.read(8 + 4 + 8 + 32)
    raw = np.fromfile(f, dtype='<f8').reshape(6, N, N, N)
q, p = raw[:3], raw[3:]
dX = q[:2] - q[:2].mean(axis=(1, 2, 3))[:, None, None, None]
realX = float(np.mean(np.sum(dX**2, axis=0))); realP = float(np.mean((q[2] - q[2].mean())**2))
# per-shell chi^2: |c_n|^2 summed over the shell (both signs, both X components) vs expectation
qh = np.fft.fftn(q, axes=(1, 2, 3), norm='forward')
nf = np.rint(np.fft.fftfreq(N)*N)
N2 = (nf[:, None, None]**2 + nf[None, :, None]**2 + nf[None, None, :]**2).astype(int)
z = []; pv = []
for key in keys:
    sel = N2 == int(key)
    if not sel.any() or 2*np.pi/L*np.sqrt(key) > 8.:  # MATCH_L12 also holds the cutoff-10 shells
        continue
    obs = np.sum(abs(qh[0][sel])**2 + abs(qh[1][sel])**2)
    i = lookup[int(key)]
    # independent pairs = mult/2; X has 2 real components each with complex coefficient -> sum over 2x2 cov eigenvalues
    Cx = (E[i][[0, 1]] @ E[i][[0, 1]].T)/V  # 2x2 complex-coefficient covariance per mode
    lam = np.linalg.eigvalsh(Cx)
    npairs = sel.sum()//2
    # obs = 2 * sum_pairs sum_j lam_j * Exp(1) (each pair counted at +n and -n)
    mean = 2*npairs*lam.sum(); var = 4*npairs*np.sum(lam**2)
    z.append((obs - mean)/np.sqrt(var))
z = np.array(z)
res = dict(full_state_max_symplectic_deviation=float(max(pur)),
           X_marginal_symplectic_eigs_range=[float(xm.min()), float(xm.max())],
           X_marginal_max_at_k=float(ks[np.argmax(xm.max(axis=1))]),
           expected_X_fluct_variance=expX, realised_X_fluct_variance_N48=realX, ratio=realX/expX,
           expected_phi_variance=expP, realised_phi_variance_N48=realP,
           X_variance_share_lowest_shells={f'{ks[i]:.4f}': float(share[i]) for i in np.argsort(ks)[:6]},
           per_shell_power_z=dict(n=len(z), mean=float(z.mean()), std=float(z.std()), max_abs=float(abs(z).max()),
                                  ks_pvalue_vs_normal=float(stats.kstest(z, 'norm').pvalue)))
json.dump(res, open(outp, 'w'), indent=1)
print(json.dumps(res, indent=1))
