# Wheeler-DeWitt, k=+1, radiation E_r, Lambda: -1/2 psi'' + (x^2/2 - lam x^4/2) psi = E_r psi, psi(0)=0
def wdw_levels(lam, nlev=4, xmax=12.0, n=3000):
    xs = np.linspace(0, xmax, n + 2)[1:-1]; h = xs[1] - xs[0]
    V = 0.5 * xs ** 2 - 0.5 * lam * xs ** 4
    diag = 1.0 / h ** 2 + V
    off = -0.5 / h ** 2 * np.ones(n - 1)
    w = sla.eigh_tridiagonal(diag, off, select="i", select_range=(0, nlev - 1))[0]
    return w
