psi /= np.linalg.norm(psi)
rho0_pure = np.outer(psi, psi.conj())
t = 2.7

U, Uc = sla.expm(-1j * H * t), sla.expm(-1j * Hc * t)
record("A1 U_c = exp(-ict) U", np.max(np.abs(Uc - np.exp(-1j * c * t) * U)), 1e-11)
rt, rtc = U @ rho0_pure @ U.conj().T, Uc @ rho0_pure @ Uc.conj().T
record("A2 global state identical", np.max(np.abs(rt - rtc)), 1e-11)
record("A3 reduced state identical", np.max(np.abs(ptrace_B(rt, dA, dB) - ptrace_B(rtc, dA, dB))), 1e-11)
record("A4 [H_c,rho]=[H,rho]", np.max(np.abs((Hc @ rt - rt @ Hc) - (H @ rt - rt @ H))), 1e-11)
ev, evc = np.linalg.eigvalsh(H), np.linalg.eigvalsh(Hc)
record("A5 all energy gaps identical", np.max(np.abs(np.subtract.outer(ev, ev) - np.subtract.outer(evc, evc))), 1e-11)
# in-out amplitude is NOT invariant (a phase), in-in (closed-time-path) quantities are
