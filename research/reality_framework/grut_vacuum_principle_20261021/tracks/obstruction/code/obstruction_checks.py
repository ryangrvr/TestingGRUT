def constraint_space(HSx, eps):
    Ht = np.kron(HSx, np.eye(dC)) + np.kron(np.eye(2), HC)
    w, v = np.linalg.eigh(Ht)
    return v[:, np.abs(w - eps) < 1e-9]
P_a = constraint_space(HS, 3.0)
P_b = constraint_space(HS + 0.5 * np.eye(2), 3.0)   # shift without moving eps
P_c = constraint_space(HS + 0.5 * np.eye(2), 3.5)   # shift with eps -> eps + c
R["A21_constraint_dims"] = {"H_S,eps=3": int(P_a.shape[1]), "H_S+0.5,eps=3": int(P_b.shape[1]),
                            "H_S+0.5,eps=3.5": int(P_c.shape[1])}
proj = lambda V: V @ V.conj().T
record("A21 constraint space unchanged iff eps shifts with c", np.max(np.abs(proj(P_a) - proj(P_c))), 1e-12)
record("A22 constraint space changes if eps is held fixed (dimension drop)", 0.0 if P_b.shape[1] != P_a.shape[1] else 1.0, 0.5)

# Internal pointer coupled to H_S as an operator: g (H_S + c) x p_pointer moves the pointer by g c t
