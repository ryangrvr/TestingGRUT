ppt = np.fft.fftfreq(ngrid, d=dx) * 2 * np.pi
def pointer_shift(cs):
    phi0 = np.exp(-xg ** 2 / 2.0); phi0 /= np.linalg.norm(phi0)
    out = 0.0
    for Ek, wk in zip(np.diag(HS + cs * np.eye(2)), [0.5, 0.5]):
        # exp(-i g E p t) translates the pointer by g E t
        ph = np.fft.ifft(np.exp(-1j * g * Ek * ppt * 2.0) * np.fft.fft(phi0))
        out += wk * float((np.abs(ph) ** 2 * xg).sum())
    return out
ps0, psc = pointer_shift(0.0), pointer_shift(0.5)
