# FRW per unit comoving volume: L = (3/(8 pi G)) (-a adot^2/N + k N a) - N a^3 rho
def constraint(rho_total):
    Lag = 3 / (8 * sp.pi * Gn) * (-a * sp.diff(a, Ts) ** 2 / N + k * N * a) - N * a ** 3 * rho_total
    return sp.simplify(sp.diff(Lag, N))
c0 = constraint(rho_m + rho_L)
cphys = constraint(rho_m + Cs + rho_L)
crel = constraint((rho_m + Cs) + (rho_L - Cs))
