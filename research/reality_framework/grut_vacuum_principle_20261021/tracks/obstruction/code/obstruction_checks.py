def record(name, value, tol, kind="max_abs_deviation"):
    ok = bool(abs(value) <= tol)
    checks.append({"name": name, kind: float(value), "tol": tol, "pass": ok})
    return ok


def rand_herm(d):
    X = rng.normal(size=(d, d)) + 1j * rng.normal(size=(d, d))
    return (X + X.conj().T) / 2


def ptrace_B(rho, dA, dB):
    return np.trace(rho.reshape(dA, dB, dA, dB), axis1=1, axis2=3)


def ptrace_A(rho, dA, dB):
    return np.trace(rho.reshape(dA, dB, dA, dB), axis1=0, axis2=2)


def vn(rho):
    w = np.linalg.eigvalsh(rho)
    w = w[w > 1e-15]
    return float(-np.sum(w * np.log(w)))


def relent(rho, sigma):
    return float(np.real(np.trace(rho @ (sla.logm(rho) - sla.logm(sigma)))))


