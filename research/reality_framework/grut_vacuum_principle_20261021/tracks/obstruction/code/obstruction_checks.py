# A. Fixed-background finite QM
# ---------------------------------------------------------------------------------------
dA, dB = 2, 3
d = dA * dB
HA, HB, HAB = rand_herm(dA), rand_herm(dB), 0.3 * rand_herm(d)
H = np.kron(HA, np.eye(dB)) + np.kron(np.eye(dA), HB) + HAB
c = 7.31  # arbitrary c-number shift
Hc = H + c * np.eye(d)
