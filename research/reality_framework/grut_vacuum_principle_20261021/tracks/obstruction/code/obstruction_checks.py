record("A6 in-out amplitude acquires exactly exp(-ict)", abs(ampc - np.exp(-1j * c * t) * amp), 1e-11)
R["A6_inout_phase_difference_rad"] = float(np.angle(ampc / amp))

beta = 0.8
G = sla.expm(-beta * H); Z = np.trace(G).real
Gc = sla.expm(-beta * Hc); Zc = np.trace(Gc).real
record("A7 normalized Gibbs state identical", np.max(np.abs(G / Z - Gc / Zc)), 1e-12)
record("A8 Z_c = exp(-beta c) Z (relative)", abs(Zc / (math.exp(-beta * c) * Z) - 1), 1e-12)
F, Fc = -math.log(Z) / beta, -math.log(Zc) / beta
record("A9 free energy shifts by exactly c (non-invariant label)", abs((Fc - F) - c), 1e-10)
R["A9_free_energy"] = {"F": F, "F_c": Fc, "difference": Fc - F, "c": c}

# KMS: omega(A sigma_{i beta}(B)) = omega(B A), with sigma generated by H or H_c
gam = G / Z
Aop, Bop = rand_herm(d), rand_herm(d)
def sig(Hx, s, X):
    return sla.expm(1j * Hx * s) @ X @ sla.expm(-1j * Hx * s)
lhs = np.trace(gam @ Aop @ sig(H, 1j * beta, Bop))
lhs_c = np.trace(gam @ Aop @ sig(Hc, 1j * beta, Bop))
rhs = np.trace(gam @ Bop @ Aop)
record("A10 KMS holds with H", abs(lhs - rhs), 1e-8)
record("A11 KMS holds with H_c (same automorphisms)", abs(lhs_c - rhs), 1e-8)

# Modular data of a faithful global state depend only on the state
rho_mix = 0.7 * rt + 0.3 * np.eye(d) / d  # faithful
rA, rB = ptrace_B(rho_mix, dA, dB), ptrace_A(rho_mix, dA, dB)
KA = -sla.logm(rA)  # one-sided modular Hamiltonian, unique once Tr rho_A = 1
record("A12 exp(-K_A) has unit trace (no additive freedom left)", abs(np.trace(sla.expm(-KA)) - 1), 1e-12)
# Writing rho_A = exp(-K)/Z leaves K defined up to K -> K + k; the normalized state is unchanged
k_shift = 3.3
record("A13 exp(-(K+k))/Tr exp(-(K+k)) = rho_A",
       np.max(np.abs(sla.expm(-(KA + k_shift)) / np.trace(sla.expm(-(KA + k_shift))) - rA)), 1e-12)

# Sigma = Delta S_A + beta Delta E_B = I(A:B) + D(rho_B || gamma_B) for a product Gibbs preparation
rhoA0 = np.array([[0.8, 0.2], [0.2, 0.2]], dtype=complex)
gB = sla.expm(-beta * HB); gB /= np.trace(gB)
prep = np.kron(rhoA0, gB)
def sigma_terms(HBx, HBfor_gibbs):
    gBx = sla.expm(-beta * HBfor_gibbs); gBx /= np.trace(gBx)
    Hx = np.kron(HA, np.eye(dB)) + np.kron(np.eye(dA), HBx) + HAB
    Ux = sla.expm(-1j * Hx * t)
    r = Ux @ prep @ Ux.conj().T
    a_, b_ = ptrace_B(r, dA, dB), ptrace_A(r, dA, dB)
    dS = vn(a_) - vn(rhoA0)
    dE = np.trace(HBx @ (b_ - gB)).real
    Sig = dS + beta * dE
    I = vn(a_) + vn(b_) - vn(r)
    D = relent(b_, gBx)
    return Sig, I + D
s0, id0 = sigma_terms(HB, HB)
s1, id1 = sigma_terms(HB + c * np.eye(dB), HB + c * np.eye(dB))
record("A14 Sigma = I + D (H_B)", s0 - id0, 1e-9)
record("A15 Sigma invariant under H_B -> H_B + c", s1 - s0, 1e-9)
R["A14_Sigma"] = s0

# Jarzynski with a two-point measurement and piecewise-constant protocol H(lambda_k)
H0q = np.array([[1.0, 0.0], [0.0, -1.0]])
Vq = np.array([[0.0, 1.0], [1.0, 0.0]])
lams = np.linspace(0.0, 1.5, 7)
def jarzynski(cfun):
    Hs = [0.5 * H0q + l * Vq + cfun(l) * np.eye(2) for l in lams]
    e0, v0 = np.linalg.eigh(Hs[0])
    p0 = np.exp(-beta * e0); p0 /= p0.sum()
    Utot = np.eye(2, dtype=complex)
    for Hk in Hs[1:]:
        Utot = sla.expm(-1j * Hk * 0.4) @ Utot
    e1, v1 = np.linalg.eigh(Hs[-1])
    avg, meanW = 0.0, 0.0
    for n in range(2):
        for m in range(2):
            pmn = abs(v1[:, m].conj() @ Utot @ v0[:, n]) ** 2
            W = e1[m] - e0[n]
            avg += p0[n] * pmn * math.exp(-beta * W)
            meanW += p0[n] * pmn * W
    dF = (-math.log(np.exp(-beta * e1).sum()) + math.log(np.exp(-beta * e0).sum())) / beta
    return avg, math.exp(-beta * dF), meanW, dF
j0 = jarzynski(lambda l: 0.0)
jc = jarzynski(lambda l: c)
jl = jarzynski(lambda l: 2.0 * l)  # lambda-dependent c-number shift
record("A16 Jarzynski holds, c=0", j0[0] - j0[1], 1e-10)
record("A17 Jarzynski holds, constant c; <W> unchanged", max(abs(jc[0] - jc[1]), abs(jc[2] - j0[2])), 1e-10)
record("A18 Jarzynski holds, c(lambda); <W> and dF both shift by c(1)-c(0)=3",
       max(abs(jl[0] - jl[1]), abs((jl[2] - j0[2]) - 3.0), abs((jl[3] - j0[3]) - 3.0)), 1e-10)
R["A18_work_shift"] = {"meanW_c0": j0[2], "meanW_clam": jl[2], "dF_c0": j0[3], "dF_clam": jl[3]}

# Internal control ("piston"): c(x) depending on a dynamical coordinate is a force
ngrid, L = 400, 24.0
xg = np.linspace(-L / 2, L / 2, ngrid); dx = xg[1] - xg[0]
lap = (np.diag(np.ones(ngrid - 1), 1) + np.diag(np.ones(ngrid - 1), -1) - 2 * np.eye(ngrid)) / dx ** 2
Mp, wp = 1.0, 0.5
Hpiston = -lap / (2 * Mp) + np.diag(0.5 * Mp * wp ** 2 * xg ** 2)
Hq = 0.5 * H0q
def piston_run(cfun):
    Htot = np.kron(Hq, np.eye(ngrid)) + np.kron(np.eye(2), Hpiston) + np.kron(np.eye(2), np.diag(cfun(xg)))
    phi0 = np.exp(-(xg - 1.0) ** 2 / 2.0); phi0 /= np.linalg.norm(phi0)
    q0 = np.array([1.0, 1.0]) / math.sqrt(2)
    st = np.kron(q0, phi0).astype(complex)
    st = expm_multiply(-1j * Htot * 3.0, st)
    probx = (np.abs(st.reshape(2, ngrid)) ** 2).sum(axis=0)
    return float((probx * xg).sum())
x_c0 = piston_run(lambda x: 0 * x)
x_cconst = piston_run(lambda x: 0 * x + c)
kappa = 0.2
x_cx = piston_run(lambda x: kappa * x)
record("A19 x-independent c leaves the internal control's motion unchanged", x_cconst - x_c0, 1e-9)
# harmonic piston: force -kappa displaces equilibrium by -kappa/(M w^2); <x(t)> = x0 cos wt - (kappa/Mw^2)(1-cos wt)
pred = -kappa / (Mp * wp ** 2) * (1 - math.cos(wp * 3.0))
record("A20 c(x)=kappa x moves the control by the predicted amount (grid error tol 1e-3)", (x_cx - x_c0) - pred, 1e-3)
