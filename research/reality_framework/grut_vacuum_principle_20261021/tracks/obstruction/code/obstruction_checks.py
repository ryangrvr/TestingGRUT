Hop = lambda u: sp.I * sp.diff(u, tt)
Pop = lambda u: -sp.I * sp.diff(u, xx)
Kop = lambda u: sp.I * (xx * sp.diff(u, tt) + tt * sp.diff(u, xx))
comm_KP = sp.simplify(Kop(Pop(f)) - Pop(Kop(f)))
B1 = sp.simplify(comm_KP - sp.I * Hop(f))  # [K,P] = i H with H = i d/dt, P = -i d/dx, K = i(x d_t + t d_x)
